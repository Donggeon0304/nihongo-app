/**
 * 일본어 카나 문자열을 자연스러운 한글 발음으로 변환
 * @param text 일본어 카나 (히라가나/가타카나)
 * @returns 친절한 한글 발음 (예: "아리가토-고자이마스")
 */
export function kanaToHangul(text: string): string {
  if (!text) return '';

  let result = '';
  let i = 0;

  while (i < text.length) {
    const twoChars = text.slice(i, i + 2);

    // 1. 요음 체크 (きゃ 등)
    if (YOON_MAP[twoChars]) {
      result += YOON_MAP[twoChars];
      i += 2;
      continue;
    }

    const char = text[i];
    const nextChar = text[i + 1] || '';

    // 2. 촉음 (っ, ッ) 처리 -> 다음 글자에 따라 받침(ㅅ/ㄱ/ㅂ) 또는 멈춤
    if (char === 'っ' || char === 'ッ') {
      result += 'ㅅ';
      i++;
      continue;
    }

    // 3. 발음 (ん, ン) 처리
    if (char === 'ん' || char === 'ン') {
      // 다음 글자가 마/바/파 행이면 'ㅁ', 카/가 행이면 'ㅇ', 그 외는 'ㄴ'
      if (['ま', 'み', 'む', 'め', 'も', 'ば', 'び', 'ぶ', 'べ', 'ぼ', 'ぱ', 'ぴ', 'ぷ', 'ぺ', 'ぽ'].includes(nextChar)) {
        result += 'ㅁ';
      } else if (['か', 'き', 'く', 'け', 'こ', 'が', 'ぎ', 'ぐ', 'げ', 'ご'].includes(nextChar)) {
        result += 'ㅇ';
      } else {
        result += 'ㄴ';
      }
      i++;
      continue;
    }

    // 4. 장음 부호 (ー) 처리
    if (char === 'ー' || char === '-') {
      result += '-';
      i++;
      continue;
    }

    // 5. 기본 글자 매핑
    if (KANA_TO_HANGUL_MAP[char]) {
      result += KANA_TO_HANGUL_MAP[char];
    } else {
      result += char; // 한자, 공백, 구두점 등은 그대로 유지
    }

    i++;
  }

  // 받침 부착 및 미세 조정
  return cleanHangulReading(result);
}

/**
 * 받침 결합 및 발음 정리 (예: "스ㅅ테" -> "슷테", "아ㅇ" -> "앙")
 */
function cleanHangulReading(raw: string): string {
  // 대표적인 조사 'は(와)' 회화 발음 처리
  return raw
    .replace(/하(?=\s|$)/g, '와')
    .replace(/오(?=\s)/g, '오')
    .replace(/스ㅅ/g, '슷')
    .replace(/마ㅅ/g, '맛')
    .replace(/이ㅅ/g, '잇')
    .replace(/키ㅅ/g, '킷')
    .replace(/타ㅅ/g, '탓')
    .replace(/테ㅅ/g, '텟')
    .replace(/토ㅅ/g, '톳')
    .replace(/코ㅅ/g, '콧')
    .replace(/쿠ㅅ/g, '쿳')
    .replace(/사ㅅ/g, '삿')
    .replace(/모ㅅ/g, '못')
    .replace(/니ㅅ/g, '닛')
    .replace(/치ㅅ/g, '칫')
    .replace(/포ㅅ/g, '폿')
    .replace(/라ㅅ/g, '랏')
    .replace(/로ㅅ/g, '롯')
    .replace(/세ㅅ/g, '셋')
    .replace(/하ㅅ/g, '핫')
    .replace(/후ㅅ/g, '훗')
    .replace(/유ㅅ/g, '윳')
    .replace(/요ㅅ/g, '욧')
    .replace(/야ㅅ/g, '얏');
}
